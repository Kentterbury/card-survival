const missing = Object.entries(ART).filter(([, n]) => !icons[n]);
if (missing.length) {
  console.error('unknown icons:', missing);
  process.exit(1);
}
const dupes = Object.values(ART).filter((n, i, a) => a.indexOf(n) !== i);
if (dupes.length) {
  console.error('icons used twice:', dupes);
  process.exit(1);
}
const lines = Object.entries(ART).map(([id, n]) => `  ${id}: ${JSON.stringify(icons[n].body)},`);
writeFileSync(new URL('../src/ui/spellArt.ts', import.meta.url), `// Generated by tools/build-spell-art.mjs from game-icons.net (CC BY 3.0, https://game-icons.net).
// Do not edit by hand.

/** Spell card id → SVG body in a 512×512 view box (fill is currentColor). */
export const SPELL_ART: Record<string, string> = {
${lines.join('\n')}
};
`);
console.log('wrote', Object.keys(ART).length, 'spell icons');
